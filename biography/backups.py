"""Private, resumable backups of a fixed catalog cut and its retained CAS bytes.

This module does not determine physical independence. A second directory can be
on the same disk. Credential stores and external source roots are never scanned;
retained source bytes can themselves contain secrets, so all output is private.
"""

from __future__ import annotations

from datetime import datetime, timezone
from contextlib import closing, contextmanager
import errno
import fcntl
import hashlib
import json
import os
from pathlib import Path
import re
import sqlite3
import stat
import time
from typing import Callable
import uuid

from .storage import (CHUNK_BYTES, DEFAULT_RESERVE_BYTES, FileSnapshot,
                      ImportPaused, IntegrityError, SpaceGuard,
                      SourceChangedError, fsync_directory, hash_file)


FORMAT = "biography-retained-originals-backup"
VERSION = 1
MAX_MANIFEST_BYTES = 64 * 1024**2
_HASH = re.compile(r"[0-9a-f]{64}\Z")


class BackupError(RuntimeError):
    """A backup is incomplete, unsafe, inconsistent, or incompatible."""


def _now() -> str:
    return datetime.now(timezone.utc).isoformat()


def _path(path: Path) -> Path:
    path = Path(os.path.abspath(path))
    for item in (path, *path.parents):
        if item.is_symlink():
            raise BackupError("Backup paths cannot contain symlinks")
    return path


def _digest_name(digest: str) -> str:
    if not isinstance(digest, str) or not _HASH.fullmatch(digest):
        raise BackupError("Invalid object SHA-256")
    return f"objects/sha256/{digest[:2]}/{digest}"


def _member(root: Path, name: str) -> Path:
    # Catalog and object filenames are generated by this module, never accepted
    # as arbitrary relative paths from a manifest.
    if (not isinstance(name, str) or "\\" in name or ":" in name or "\x00" in name
            or Path(name).is_absolute() or ".." in Path(name).parts
            or Path(name).as_posix() != name or name in ("", ".")):
        raise BackupError("Unsafe backup member path")
    return _path(root / name)


def _private(path: Path, directory: bool, external: bool) -> None:
    _path(path)
    os.chmod(path, 0o700 if directory else 0o600)
    info = path.stat()
    if not external and (info.st_uid != os.getuid() or stat.S_IMODE(info.st_mode) & 0o077):
        raise BackupError("Owner-only permissions could not be enforced; native ACL evidence is required")


def _mkdir(path: Path, external: bool) -> None:
    _path(path)
    # Parents outside the backup root are not chmodded.
    missing = []
    parent = path
    while not parent.exists():
        missing.append(parent)
        parent = parent.parent
    path.mkdir(parents=True, exist_ok=True, mode=0o700)
    for parent in reversed(missing):
        _private(parent, True, external)
    _private(path, True, external)


def _space_guard(root: Path, reserve: int, capacity_paths: tuple[Path, ...]):
    if reserve < 0:
        raise ValueError("Space reserve must be nonnegative")
    guards = [SpaceGuard(root, reserve, windows_root=None)]
    for path in capacity_paths:
        capacity = _path(Path(path))
        if not capacity.is_dir():
            raise BackupError("Configured capacity path is unavailable")
        guards.append(SpaceGuard(capacity, reserve, windows_root=None))
    def check(additional: int):
        for guard in guards:
            guard(additional)
    return check


def _json_write(path: Path, value: dict, external: bool) -> None:
    payload = (json.dumps(value, sort_keys=True, allow_nan=False) + "\n").encode()
    if len(payload) > MAX_MANIFEST_BYTES:
        raise BackupError("Backup manifest exceeds its size bound")
    temporary = _path(path.with_name(path.name + ".part"))
    temporary.unlink(missing_ok=True)
    descriptor = os.open(temporary, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    try:
        with os.fdopen(descriptor, "wb") as handle:
            handle.write(payload)
            handle.flush()
            os.fsync(handle.fileno())
        _private(temporary, False, external)
        os.replace(temporary, path)
        fsync_directory(path.parent)
    finally:
        temporary.unlink(missing_ok=True)


def _read_json(path: Path) -> dict:
    path = _path(path)
    if path.stat().st_size > MAX_MANIFEST_BYTES:
        raise BackupError("Backup manifest exceeds its size bound")
    value = json.loads(path.read_bytes())
    if not isinstance(value, dict):
        raise BackupError("Invalid backup manifest")
    return value


def _connect(path: Path) -> sqlite3.Connection:
    connection = sqlite3.connect(path.as_uri() + "?mode=ro", uri=True, timeout=0.1)
    connection.execute("PRAGMA query_only=ON")
    return connection


@contextmanager
def _writer_lock(root: Path, external: bool):
    path = _path(root / ".writer.lock")
    descriptor = os.open(path, os.O_RDWR | os.O_CREAT | getattr(os, "O_NOFOLLOW", 0), 0o600)
    try:
        _private(path, False, external)
        try:
            fcntl.flock(descriptor, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except BlockingIOError as error:
            raise ImportPaused("backup_writer_active") from error
        yield
    finally:
        os.close(descriptor)


def _checks(connection: sqlite3.Connection) -> None:
    if connection.execute("PRAGMA integrity_check").fetchall() != [("ok",)]:
        raise BackupError("Catalog failed integrity_check")
    if connection.execute("PRAGMA foreign_key_check").fetchone() is not None:
        raise BackupError("Catalog failed foreign_key_check")


def _inventory(connection: sqlite3.Connection):
    for digest, length, source_path in connection.execute(
            "SELECT sha256,bytes,path FROM objects ORDER BY sha256"):
        _digest_name(digest)
        if not isinstance(length, int) or length < 0 or not isinstance(source_path, str):
            raise BackupError("Invalid catalog object inventory")
        yield digest, length, source_path


def _watermark(connection: sqlite3.Connection) -> dict:
    counts = {name: connection.execute(f'SELECT count(*) FROM "{name}"').fetchone()[0]
              for name in ("objects", "files", "events", "evidence", "sources", "imports")}
    return {"counts": counts,
            "last_event_rowid": connection.execute("SELECT max(rowid) FROM events").fetchone()[0],
            "object_bytes": connection.execute("SELECT coalesce(sum(bytes),0) FROM objects").fetchone()[0],
            "imports": [dict(zip(("id", "source_id", "status", "completed_files", "completed_bytes"), row))
                        for row in connection.execute("SELECT id,source_id,status,completed_files,completed_bytes "
                                                      "FROM imports ORDER BY id")]}


def _catalog_cut(database: Path, destination: Path, guard: Callable[[int], None],
                 timeout: float, wal_limit: int, external: bool,
                 progress: Callable[[dict], None] | None) -> None:
    if timeout <= 0 or wal_limit < 0:
        raise ValueError("Snapshot timeout must be positive and WAL growth bound nonnegative")
    temporary = _path(destination.with_suffix(".sqlite3.part"))
    temporary.unlink(missing_ok=True)  # SQLite backup cannot resume an incomplete cut.
    wal = database.with_name(database.name + "-wal")
    initial_wal = wal.stat().st_size if wal.exists() else 0
    started = time.monotonic()
    with closing(_connect(database)) as source:
        page_size = source.execute("PRAGMA page_size").fetchone()[0]
        guard(source.execute("PRAGMA page_count").fetchone()[0] * page_size)
        target = sqlite3.connect(temporary)
        try:
            _private(temporary, False, external)
            last_space_check = started
            last_remaining = None
            allocated_since_check = 0
            def step(status, remaining, total):
                nonlocal last_space_check, last_remaining, allocated_since_check
                current_time = time.monotonic()
                if current_time - started > timeout:
                    raise ImportPaused("snapshot_timeout", timeout_seconds=timeout)
                growth = (wal.stat().st_size if wal.exists() else 0) - initial_wal
                if growth > wal_limit:
                    raise ImportPaused("snapshot_wal_growth", growth_bytes=growth, limit_bytes=wal_limit)
                if last_remaining is not None:
                    allocated_since_check += max(last_remaining - remaining, 0) * page_size
                last_remaining = remaining
                # The initial guard reserves the entire catalog. Cross-VM
                # capacity probes can be expensive, so bound their frequency
                # while still checking time and WAL growth on every step.
                if current_time - last_space_check >= 1 or allocated_since_check >= 64 * 1024**2:
                    guard(max(remaining, 0) * page_size)
                    last_space_check = current_time
                    allocated_since_check = 0
                if progress:
                    progress({"stage": "catalog_cut", "pages_remaining": remaining, "pages_total": total})
            # No long-lived read transaction is pinned. Writers may make the
            # backup restart; the deadline and WAL budget bound that work.
            source.backup(target, pages=1024, progress=step, sleep=0.05)
        finally:
            target.close()
    with temporary.open("rb") as handle:
        os.fsync(handle.fileno())
    os.link(temporary, destination)  # Atomic publication without overwrite.
    temporary.unlink()
    fsync_directory(destination.parent)


def _source_object(vaultroot: Path, name: str) -> Path:
    if ".." in Path(name).parts:
        raise BackupError("Object path contains traversal")
    path = _path(Path(name) if Path(name).is_absolute() else vaultroot / name)
    try:
        path.relative_to(vaultroot / "objects")
    except ValueError as error:
        raise BackupError("Catalog object path escapes the configured CAS root") from error
    return path


def _verify_object(path: Path, digest: str, length: int) -> None:
    actual, size = hash_file(_path(path))
    if actual != digest or size != length:
        raise IntegrityError(f"Backup object failed independent readback: {digest}")


def _copy_object(source: Path, destination: Path, digest: str, length: int,
                 guard: Callable[[int], None], external: bool) -> bool:
    if destination.exists():
        _private(destination, False, external)
        _verify_object(destination, digest, length)
        _path(destination.with_name(destination.name + ".part")).unlink(missing_ok=True)
        return False
    guard(length)
    _mkdir(destination.parent, external)
    temporary = _path(destination.with_name(destination.name + ".part"))
    temporary.unlink(missing_ok=True)
    before = FileSnapshot.capture(source)
    if before.size != length:
        raise IntegrityError("Catalog object length differs from retained bytes")
    descriptor = os.open(source, os.O_RDONLY | getattr(os, "O_NOFOLLOW", 0))
    try:
        with os.fdopen(descriptor, "rb") as reader, temporary.open("xb") as writer:
            opened = os.fstat(reader.fileno())
            if (opened.st_dev, opened.st_ino) != (before.device, before.inode):
                raise IntegrityError("Retained object was replaced before copying")
            _private(temporary, False, external)
            digesting, copied = hashlib.sha256(), 0
            while data := reader.read(CHUNK_BYTES):
                guard(len(data))
                writer.write(data)
                digesting.update(data)
                copied += len(data)
                if copied > length:
                    raise IntegrityError("Retained object grew while copying")
            writer.flush()
            os.fsync(writer.fileno())
        if FileSnapshot.capture(source) != before:
            raise IntegrityError("Retained object changed while copying")
        if digesting.hexdigest() != digest or copied != length:
            raise IntegrityError("Retained object failed its declared hash or length")
        # Independent readback of destination bytes, not the streaming hash.
        _verify_object(temporary, digest, length)
        try:
            os.link(temporary, destination)
        except FileExistsError:
            _verify_object(destination, digest, length)
        fsync_directory(destination.parent)
        return True
    finally:
        temporary.unlink(missing_ok=True)


class _BoundedReader:
    """Do not chase a live append-only ledger beyond its observed byte cut."""

    def __init__(self, handle, length):
        self.handle, self.remaining = handle, length

    def read(self, size=-1):
        size = self.remaining if size < 0 else min(size, self.remaining)
        value = self.handle.read(size)
        self.remaining -= len(value)
        return value


def _ledger_info(path: Path, cut: sqlite3.Connection, covered=None) -> dict:
    # ijson is already an application dependency. Event parsing avoids loading
    # huge source_ready object arrays or whole ledgers into memory.
    import ijson
    before = FileSnapshot.capture(_path(path))
    if not before.size:
        raise BackupError("empty_ledger")
    read_bytes = 0
    def bounded_hash(length):
        nonlocal read_bytes
        read_bytes += length
        if read_bytes > before.size:
            raise SourceChangedError("ledger_changed")
    digest, size = hash_file(path, snapshot=before, progress=bounded_hash)
    records = objects = 0
    record = None
    last = None
    try:
        with path.open("rb") as handle:
            handle.seek(-1, os.SEEK_END)
            if handle.read(1) != b"\n":
                raise BackupError("incomplete_final_record")
            handle.seek(0)
            for prefix, event, value in ijson.parse(_BoundedReader(handle, before.size), multiple_values=True):
                if prefix == "":
                    if event == "start_map":
                        if last and last.get("kind") == "footer":
                            raise BackupError("records_after_footer")
                        record = {}
                    elif event == "end_map" and record is not None:
                        if not isinstance(record.get("kind"), str):
                            raise BackupError("invalid_ledger_record")
                        if records == 0 and record["kind"] != "header":
                            raise BackupError("missing_ledger_header")
                        if record["kind"] == "object":
                            sha, length = record.get("sha256"), record.get("size")
                            _digest_name(sha)
                            match = cut.execute("SELECT bytes FROM objects WHERE sha256=?", (sha,)).fetchone()
                            if (not isinstance(length, int) or isinstance(length, bool)
                                    or match is None or match[0] != length):
                                raise BackupError("object_outside_fixed_catalog")
                            if covered is not None:
                                covered.execute("INSERT OR IGNORE INTO covered VALUES(?)", (sha,))
                            objects += 1
                        records += 1
                        last, record = record, None
                    elif event not in ("map_key",):
                        raise BackupError("invalid_ledger_record")
                elif record is not None and prefix in ("kind", "sha256", "size", "status"):
                    if event not in ("string", "number", "null", "boolean") or prefix in record:
                        raise BackupError("invalid_ledger_field")
                    record[prefix] = value
    except ijson.JSONError as error:
        raise BackupError("invalid_ledger_json") from error
    if FileSnapshot.capture(path) != before:
        raise SourceChangedError("ledger_changed")
    if not last or last.get("kind") != "footer" or last.get("status") != "complete":
        raise BackupError("ledger_not_complete")
    return {"sha256": digest, "bytes": size, "records": records, "object_records": objects}


def _ledger_plan(root: Path | None, catalog: Path, catalog_hash: str) -> dict:
    result = {"requested": root is not None, "catalog_sha256": catalog_hash,
              "observed_at": _now(), "included": [], "deferred": [],
              "mode": "stable_complete_ledgers_matching_fixed_catalog"}
    if root is None:
        result["complete"] = False
        return result
    root = _path(root)
    if not root.is_dir():
        raise BackupError("Import ledger directory is unavailable")
    paths = sorted(root.glob("*.jsonl"))
    # A small, file-backed SQLite temporary table bounds memory when millions
    # of retained objects occur across overlapping import ledgers.
    with closing(_connect(catalog)) as cut, closing(sqlite3.connect("")) as coverage:
        coverage.execute("PRAGMA temp_store=FILE")
        coverage.execute("PRAGMA temp.cache_size=-1024")
        coverage.execute("CREATE TEMP TABLE covered(sha256 TEXT PRIMARY KEY)")
        for path in paths:
            coverage.execute("SAVEPOINT ledger")
            try:
                _member(Path("/"), "manifests/" + path.name)
                info = _ledger_info(path, cut, coverage)
                result["included"].append({"name": path.name, "path": "manifests/" + path.name, **info})
                coverage.execute("RELEASE ledger")
            except (BackupError, IntegrityError, OSError) as error:
                coverage.execute("ROLLBACK TO ledger")
                coverage.execute("RELEASE ledger")
                result["deferred"].append({"name": path.name, "reason": str(error)})
        seen = {path.name for path in paths}
        result["deferred"].extend({"name": path.name, "reason": "appeared_during_ledger_scan"}
                                  for path in sorted(root.glob("*.jsonl")) if path.name not in seen)
        uncovered = sum(coverage.execute("SELECT 1 FROM covered WHERE sha256=?", (digest,)).fetchone() is None
                        for digest, _, _ in _inventory(cut))
        result["catalog_objects_without_complete_ledger"] = uncovered
    result["complete"] = not result["deferred"] and uncovered == 0
    return result


def _ledger_descriptors(manifest: dict):
    for descriptor in manifest.get("ledgers", {}).get("included", []):
        name = descriptor.get("name")
        if (not isinstance(name, str) or Path(name).name != name or not name.endswith(".jsonl")
                or descriptor.get("path") != "manifests/" + name):
            raise BackupError("Unsafe ledger descriptor")
        yield descriptor


def _verify_ledgers(root: Path, manifest: dict, cut: sqlite3.Connection) -> dict:
    coverage = manifest.get("ledgers", {})
    if coverage.get("catalog_sha256") != manifest["catalog"]["sha256"]:
        raise BackupError("Ledger inventory is not bound to the fixed catalog")
    records = ledgers = total = 0
    for descriptor in _ledger_descriptors(manifest):
        info = _ledger_info(_member(root, descriptor["path"]), cut)
        if any(info[key] != descriptor.get(key) for key in info):
            raise IntegrityError("Ledger failed manifest hash or record-count readback")
        records += info["records"]
        total += info["bytes"]
        ledgers += 1
    return {"files_verified": ledgers, "records_verified": records, "bytes_verified": total,
            "complete": coverage.get("complete", False), "deferred": coverage.get("deferred", []),
            "catalog_objects_without_complete_ledger": coverage.get("catalog_objects_without_complete_ledger")}


def _manifest(root: Path, *, complete: bool = True) -> dict:
    manifest = _read_json(_member(root, "manifest.json"))
    if manifest.get("format") != FORMAT or manifest.get("format_version") != VERSION:
        raise BackupError("Unsupported backup format")
    if complete and manifest.get("status") not in ("complete", "partial"):
        raise BackupError("Backup is not complete")
    catalog = manifest.get("catalog", {})
    if catalog and (catalog.get("path") != "catalog.sqlite3" or not _HASH.fullmatch(catalog.get("sha256", ""))):
        raise BackupError("Unsafe catalog descriptor")
    return manifest


def create_backup(database: Path, vaultroot: Path, destination: Path, *,
                  reserve_bytes: int = DEFAULT_RESERVE_BYTES,
                  snapshot_timeout: float = 600, max_wal_growth_bytes: int = 512 * 1024**2,
                  capacity_paths: tuple[Path, ...] = (),
                  manifests_dir: Path | None = None,
                  space_guard: Callable[[int], None] | None = None,
                  progress: Callable[[dict], None] | None = None,
                  externally_private: bool = False, privacy_evidence: dict | None = None) -> dict:
    """Create or resume one fixed cut. Resume rehashes every existing object.

    Use a fresh destination for the next cut. Partial cuts are restarted, while
    published cuts never advance to incorporate subsequently imported objects.
    The caller must arrange physical independence and may supply verified native
    ACL evidence on filesystems which cannot enforce POSIX owner permissions.
    """
    database, vaultroot, root = _path(database), _path(vaultroot), _path(destination)
    manifests_dir = _path(manifests_dir) if manifests_dir is not None else None
    if externally_private and not privacy_evidence:
        raise BackupError("Native privacy evidence is required for external permission enforcement")
    if (root.exists() and not (root / "manifest.json").exists()
            and any(path.name != ".writer.lock" for path in root.iterdir())):
        raise BackupError("Existing backup destination has no resumable manifest")
    _mkdir(root, externally_private)
    with _writer_lock(root, externally_private):
        return _create_backup(database, vaultroot, root, reserve_bytes=reserve_bytes,
                              snapshot_timeout=snapshot_timeout, max_wal_growth_bytes=max_wal_growth_bytes,
                              capacity_paths=capacity_paths, manifests_dir=manifests_dir,
                              space_guard=space_guard, progress=progress,
                              externally_private=externally_private, privacy_evidence=privacy_evidence)


def _create_backup(database: Path, vaultroot: Path, root: Path, *, reserve_bytes: int,
                   snapshot_timeout: float, max_wal_growth_bytes: int,
                   capacity_paths: tuple[Path, ...], manifests_dir: Path | None,
                   space_guard: Callable[[int], None] | None,
                   progress: Callable[[dict], None] | None,
                   externally_private: bool, privacy_evidence: dict | None) -> dict:
    guard = space_guard or _space_guard(root, reserve_bytes, capacity_paths)
    manifest_path = _member(root, "manifest.json")
    if manifest_path.exists():
        manifest = _manifest(root, complete=False)
        if manifest.get("source_database") != str(database) or manifest.get("source_vault") != str(vaultroot):
            raise BackupError("Resume source does not match this fixed backup")
        if manifest.get("source_manifests") != (str(manifests_dir) if manifests_dir is not None else None):
            raise BackupError("Resume import ledger directory does not match")
        if manifest.get("privacy", {}).get("externally_enforced") != externally_private:
            raise BackupError("Resume privacy enforcement does not match")
    else:
        manifest = {"format": FORMAT, "format_version": VERSION, "snapshot_id": str(uuid.uuid4()),
                    "created_at": _now(), "status": "cut_pending", "private_content": True,
                    "source_database": str(database), "source_vault": str(vaultroot),
                    "source_manifests": str(manifests_dir) if manifests_dir is not None else None,
                    "scope": "all retained CAS objects registered in this fixed catalog cut",
                    "inventory": "catalog.sqlite3:objects", "physical_independence_asserted": False,
                    "excluded": ["external source roots", "unregistered CAS files", "credential stores",
                                 "environment files outside CAS", "incomplete or unmatched import ledgers"],
                    "privacy": {"externally_enforced": externally_private,
                                "caller_supplied_evidence": privacy_evidence or {}}}
        _json_write(manifest_path, manifest, externally_private)
    state = {"status": "running", "stage": "catalog_cut", "objects_verified": 0,
             "bytes_verified": 0, "objects_newly_copied": 0, "snapshot_id": manifest["snapshot_id"]}
    last_status = 0.0
    def update(force=False):
        nonlocal last_status
        if force or time.monotonic() - last_status >= 1:
            state["updated_at"] = _now()
            _json_write(root / "status.json", state, externally_private)
            if progress:
                progress(dict(state))
            last_status = time.monotonic()
    try:
        update(True)
        catalog = _member(root, "catalog.sqlite3")
        if not catalog.exists():
            if manifest.get("catalog"):
                raise BackupError("Published fixed catalog is missing; refusing a newer cut")
            _catalog_cut(database, catalog, guard, snapshot_timeout, max_wal_growth_bytes,
                         externally_private, progress)
        _private(catalog, False, externally_private)
        actual_hash, size = hash_file(catalog)
        if manifest.get("catalog") and manifest["catalog"] != {"path": "catalog.sqlite3", "sha256": actual_hash, "bytes": size}:
            raise IntegrityError("Fixed catalog failed manifest readback")
        _member(root, "catalog.sqlite3.part").unlink(missing_ok=True)
        with closing(_connect(catalog)) as cut:
            _checks(cut)
            watermark = _watermark(cut)
            manifest.update({"status": "copying", "catalog": {"path": "catalog.sqlite3", "sha256": actual_hash,
                             "bytes": size}, "catalog_cut_at": manifest.get("catalog_cut_at", _now()),
                             "watermark": watermark})
            _json_write(manifest_path, manifest, externally_private)
            state.update({"stage": "retained_objects", "watermark": watermark,
                          "catalog_sha256": actual_hash, "catalog_cut_at": manifest["catalog_cut_at"]})
            for digest, length, original in _inventory(cut):
                source = _source_object(vaultroot, original)
                state["current_object"] = digest
                copied = _copy_object(source, _member(root, _digest_name(digest)), digest, length, guard, externally_private)
                state["objects_verified"] += 1
                state["bytes_verified"] += length
                state["objects_newly_copied"] += int(copied)
                update()
            state["stage"] = "import_ledgers"
            update(True)
            if "ledgers" not in manifest:
                manifest["ledgers"] = _ledger_plan(manifests_dir, catalog, actual_hash)
                _json_write(manifest_path, manifest, externally_private)
            for descriptor in _ledger_descriptors(manifest):
                _copy_object(_member(manifests_dir, descriptor["name"]), _member(root, descriptor["path"]),
                             descriptor["sha256"], descriptor["bytes"], guard, externally_private)
            ledger_verification = _verify_ledgers(root, manifest, cut)
        partial = manifests_dir is not None and not manifest["ledgers"]["complete"]
        manifest.update({"status": "partial" if partial else "complete", "completed_at": _now(),
                         "catalog_and_objects_complete": True,
                         "retained_evidence_complete": manifest["ledgers"]["complete"],
                         "objects_verified": state["objects_verified"], "bytes_verified": state["bytes_verified"]})
        _json_write(manifest_path, manifest, externally_private)
        state.update({"status": manifest["status"], "stage": "complete", "ledgers": ledger_verification})
        update(True)
        return manifest
    except BaseException as error:
        state.update({"status": "paused" if isinstance(error, (ImportPaused, KeyboardInterrupt)) else "failed",
                      "error_type": type(error).__name__, "reason": getattr(error, "reason", str(error)),
                      "pause_details": getattr(error, "details", {})})
        try:
            update(True)
        except OSError:
            pass  # Preserve the original error when the destination has filled.
        if not (root / "catalog.sqlite3").exists():
            _member(root, "catalog.sqlite3.part").unlink(missing_ok=True)
        if isinstance(error, OSError) and error.errno in (errno.ENOSPC, errno.EDQUOT):
            raise ImportPaused("filesystem_full", path=str(root)) from error
        raise


def verify_backup(backup: Path, *, progress: Callable[[dict], None] | None = None) -> dict:
    """Independently read back the full fixed catalog and every retained object."""
    root = _path(backup)
    manifest = _manifest(root)
    catalog = _member(root, "catalog.sqlite3")
    actual, size = hash_file(catalog)
    if (actual, size) != (manifest["catalog"]["sha256"], manifest["catalog"]["bytes"]):
        raise IntegrityError("Catalog failed manifest readback")
    objects = total = 0
    with closing(_connect(catalog)) as connection:
        _checks(connection)
        watermark = _watermark(connection)
        if watermark != manifest["watermark"]:
            raise BackupError("Catalog watermark differs from the manifest")
        for digest, length, _ in _inventory(connection):
            _verify_object(_member(root, _digest_name(digest)), digest, length)
            objects += 1
            total += length
            if progress:
                progress({"stage": "verify", "objects_verified": objects, "bytes_verified": total})
        ledger_verification = _verify_ledgers(root, manifest, connection)
    if objects != manifest["objects_verified"] or total != manifest["bytes_verified"]:
        raise BackupError("Object inventory totals differ from the manifest")
    return {"status": "partial_verified" if manifest["status"] == "partial" else "verified",
            "snapshot_id": manifest["snapshot_id"], "catalog_sha256": actual,
            "objects_verified": objects, "bytes_verified": total, "watermark": watermark,
            "ledgers": ledger_verification, "retained_evidence_complete": manifest["retained_evidence_complete"],
            "physical_independence_asserted": False}


def restore_backup(backup: Path, destination: Path, *, reserve_bytes: int = DEFAULT_RESERVE_BYTES,
                   capacity_paths: tuple[Path, ...] = (),
                   space_guard: Callable[[int], None] | None = None,
                   progress: Callable[[dict], None] | None = None,
                   externally_private: bool = False, privacy_evidence: dict | None = None) -> dict:
    """Restore into a NEW vault, validate all bytes, and remap object paths.

    The destination catalog is published only after original-byte readback,
    integrity/FK checks, and unchanged provenance counts. A failed restore leaves
    only its new private directory and no published catalog.
    """
    root, destination = _path(backup), _path(destination)
    if destination.exists():
        raise BackupError("Restore destination must be new")
    if externally_private and not privacy_evidence:
        raise BackupError("Native privacy evidence is required for restored data")
    manifest = _manifest(root)
    catalog = _member(root, "catalog.sqlite3")
    if hash_file(catalog) != (manifest["catalog"]["sha256"], manifest["catalog"]["bytes"]):
        raise IntegrityError("Catalog failed manifest readback")
    guard = space_guard or _space_guard(destination, reserve_bytes, capacity_paths)
    guard(manifest["catalog"]["bytes"] + manifest["watermark"]["object_bytes"]
          + sum(item["bytes"] for item in _ledger_descriptors(manifest)))
    _mkdir(destination, externally_private)
    temporary = _member(destination, "catalog.sqlite3.part")
    objects = total = 0
    try:
        with closing(_connect(catalog)) as source:
            _checks(source)
            if _watermark(source) != manifest["watermark"]:
                raise BackupError("Catalog watermark differs from the manifest")
            for digest, length, _ in _inventory(source):
                _copy_object(_member(root, _digest_name(digest)), _member(destination, _digest_name(digest)),
                             digest, length, guard, externally_private)
                objects += 1
                total += length
                if progress:
                    progress({"stage": "restore_objects", "objects_verified": objects, "bytes_verified": total})
            for descriptor in _ledger_descriptors(manifest):
                _copy_object(_member(root, descriptor["path"]), _member(destination, descriptor["path"]),
                             descriptor["sha256"], descriptor["bytes"], guard, externally_private)
            ledger_verification = _verify_ledgers(destination, manifest, source)
        # Stream exactly one catalog copy. A second SQLite backup would create
        # needless space pressure on a large archive.
        _copy_object(catalog, temporary, manifest["catalog"]["sha256"], manifest["catalog"]["bytes"],
                     guard, externally_private)
        restored = sqlite3.connect(temporary)
        try:
            restored.execute("PRAGMA journal_mode=DELETE")
            # Bound the rollback journal while remapping many paths.
            rows = restored.execute("SELECT sha256 FROM objects ORDER BY sha256")
            while batch := rows.fetchmany(1000):
                with restored:
                    restored.executemany("UPDATE objects SET path=? WHERE sha256=?",
                                         [(str(_member(destination, _digest_name(row[0]))), row[0]) for row in batch])
                guard(0)
            _checks(restored)
            if _watermark(restored) != manifest["watermark"]:
                raise BackupError("Restored provenance watermark differs from the catalog cut")
            for digest, length, path in _inventory(restored):
                if path != str(_member(destination, _digest_name(digest))):
                    raise BackupError("Restored catalog points outside its new CAS")
            if objects != manifest["objects_verified"] or total != manifest["bytes_verified"]:
                raise BackupError("Restored object inventory differs from the manifest")
        finally:
            restored.close()
        with temporary.open("rb") as handle:
            os.fsync(handle.fileno())
        restored_hash, restored_size = hash_file(temporary)
        result = {"status": "partial_restored_and_verified" if manifest["status"] == "partial" else "restored_and_verified",
                  "snapshot_id": manifest["snapshot_id"],
                  "backup_catalog_sha256": manifest["catalog"]["sha256"],
                  "restored_catalog_sha256": restored_hash, "restored_catalog_bytes": restored_size,
                  "objects_verified": objects, "bytes_verified": total,
                  "ledgers": ledger_verification, "retained_evidence_complete": manifest["retained_evidence_complete"],
                  "watermark": manifest["watermark"], "original_bytes_read_back": True,
                  "all_object_paths_remapped": True, "physical_independence_asserted": False,
                  "privacy": {"externally_enforced": externally_private,
                              "caller_supplied_evidence": privacy_evidence or {}}}
        _json_write(destination / "restore-report.json", result, externally_private)
        os.link(temporary, destination / "catalog.sqlite3")
        temporary.unlink()
        fsync_directory(destination)
        return result
    finally:
        temporary.unlink(missing_ok=True)


